-- Ejecutar en BOMERP_APP después de S08_02. Una liquidación puede integrar
-- un solo lote de exportación. El exportador es externo al sistema.

CREATE TABLE LOTES_EXPORTACION (
    ID_LOTE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA DATE NOT NULL,
    ESTADO VARCHAR2(20 CHAR) DEFAULT 'BORRADOR' NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_PREPARACION TIMESTAMP,
    CONSTRAINT CK_LOTE_EXP_ESTADO CHECK (ESTADO IN ('BORRADOR', 'PREPARADO'))
);

CREATE TABLE LOTE_EXPORTACION_PARTIDAS (
    ID_PARTIDA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_LOTE NUMBER NOT NULL,
    ID_LIQUIDACION_G1 NUMBER NOT NULL,
    LECTURA_DECIMAL NUMBER(12,6) NOT NULL,
    CONSTRAINT FK_LOTE_PART_LOTE FOREIGN KEY (ID_LOTE)
        REFERENCES LOTES_EXPORTACION (ID_LOTE) ON DELETE CASCADE,
    CONSTRAINT FK_LOTE_PART_LIQ FOREIGN KEY (ID_LIQUIDACION_G1)
        REFERENCES LIQUIDACIONES_G1 (ID_LIQUIDACION_G1),
    CONSTRAINT UQ_LOTE_PART_LIQ UNIQUE (ID_LIQUIDACION_G1),
    CONSTRAINT CK_LOTE_PART_LECTURA CHECK (LECTURA_DECIMAL >= 0)
);

CREATE INDEX IX_LOTE_EXP_FECHA ON LOTES_EXPORTACION (FECHA, ID_LOTE);
CREATE INDEX IX_LOTE_PART_LOTE ON LOTE_EXPORTACION_PARTIDAS (ID_LOTE);
