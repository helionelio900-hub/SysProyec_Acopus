-- Ejecutar conectado al esquema de la aplicación en XEPDB1.
-- Migración aditiva: las operaciones anteriores mantienen sus IDs y vínculos.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF
DECLARE
    cantidad NUMBER;
BEGIN
    SELECT COUNT(*) INTO cantidad FROM USER_TABLES
        WHERE TABLE_NAME IN ('MINEROS', 'CENTROS_ACOPIO', 'TRANSACCIONES_G2');
    IF cantidad <> 3 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Faltan tablas previas de SITRA: MINEROS, CENTROS_ACOPIO o TRANSACCIONES_G2. No se aplicó la migración.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'TRANSACCIONES_G2'
        AND COLUMN_NAME IN ('ID_CENTRO_ACOPIO', 'ANULADA', 'ID_RECEPCION_MAYORISTA');
    IF cantidad <> 3 THEN
        RAISE_APPLICATION_ERROR(-20002, 'El esquema requiere las migraciones S08 y S09 anteriores. No se aplicó la migración.');
    END IF;
    SELECT COUNT(*) INTO cantidad FROM USER_TABLES WHERE TABLE_NAME = 'COMPRAS_G2';
    IF cantidad = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE COMPRAS_G2 (
            ID_COMPRA_G2 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ID_MINERO NUMBER NOT NULL REFERENCES MINEROS(ID_MINERO),
            ID_CENTRO_ACOPIO NUMBER NOT NULL REFERENCES CENTROS_ACOPIO(ID_CENTRO_ACOPIO),
            FECHA_COMPRA TIMESTAMP NOT NULL
        )';
    END IF;
    SELECT COUNT(*) INTO cantidad FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = 'TRANSACCIONES_G2' AND COLUMN_NAME = 'ID_COMPRA_G2';
    IF cantidad = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE TRANSACCIONES_G2 ADD (ID_COMPRA_G2 NUMBER)';
    END IF;
    SELECT COUNT(*) INTO cantidad FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'FK_G2_COMPRA';
    IF cantidad = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE TRANSACCIONES_G2 ADD CONSTRAINT FK_G2_COMPRA
            FOREIGN KEY (ID_COMPRA_G2) REFERENCES COMPRAS_G2(ID_COMPRA_G2)';
    END IF;
    SELECT COUNT(*) INTO cantidad FROM USER_INDEXES WHERE INDEX_NAME = 'IX_G2_COMPRA';
    IF cantidad = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_G2_COMPRA ON TRANSACCIONES_G2(ID_COMPRA_G2)';
    END IF;
END;
/
PROMPT Cabecera y detalle de compras disponibles.
EXIT
