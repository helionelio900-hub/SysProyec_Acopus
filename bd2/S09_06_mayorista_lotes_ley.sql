-- Migración aditiva. Ejecutar en el esquema real de SITRA-ORO, XEPDB1.
-- Lote recibido = MAYORISTA_RECEPCIONES. N:N con LEYES_ORO mediante RECEPCION_LEYES.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF
DECLARE
    n NUMBER;
BEGIN
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME IN ('MAYORISTA_RECEPCIONES', 'LOTE_RECEPCIONES');
    IF n <> 2 THEN RAISE_APPLICATION_ERROR(-20001, 'Faltan las migraciones previas de recepciones y lotes'); END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'MAYORISTA_RECEPCIONES' AND COLUMN_NAME = 'REVISION_LEY';
    IF n = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE MAYORISTA_RECEPCIONES ADD REVISION_LEY NUMBER(19) DEFAULT 0 NOT NULL'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'LEYES_ORO';
    IF n = 0 THEN EXECUTE IMMEDIATE 'CREATE TABLE LEYES_ORO (
        ID_LEY NUMBER(19) PRIMARY KEY,
        VALOR NUMBER(7,4) NOT NULL CONSTRAINT UQ_LEY_VALOR UNIQUE,
        CONSTRAINT CK_LEY_VALOR CHECK (VALOR > 0 AND VALOR <= 100),
        CONSTRAINT CK_LEY_ID CHECK (ID_LEY = VALOR * 10000))'; END IF;
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'RECEPCION_LEYES';
    IF n = 0 THEN EXECUTE IMMEDIATE 'CREATE TABLE RECEPCION_LEYES (
        ID_DETALLE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ID_RECEPCION NUMBER NOT NULL REFERENCES MAYORISTA_RECEPCIONES(ID_RECEPCION),
        ID_LEY NUMBER(19) NOT NULL REFERENCES LEYES_ORO(ID_LEY),
        ONZA_USD NUMBER(14,4) NOT NULL CHECK (ONZA_USD > 0),
        PORCENTAJE NUMBER(7,4) NOT NULL CHECK (PORCENTAJE >= 0 AND PORCENTAJE < 100),
        TIPO_CAMBIO NUMBER(10,4) NOT NULL CHECK (TIPO_CAMBIO > 0),
        PESO_SIN_FUNDIR_G NUMBER(10,3) NOT NULL CHECK (PESO_SIN_FUNDIR_G > 0),
        PESO_FUNDIDO_G NUMBER(10,3) NOT NULL CHECK (PESO_FUNDIDO_G > 0),
        PRECIO_USD NUMBER(18,2) NOT NULL,
        PRECIO_PEN NUMBER(18,2) NOT NULL CHECK (PRECIO_PEN > 0),
        TOTAL_PEN NUMBER(24,2) NOT NULL,
        CONSTRAINT CK_RLEY_PESOS CHECK (PESO_FUNDIDO_G <= PESO_SIN_FUNDIR_G),
        CONSTRAINT UQ_RECEPCION_LEY UNIQUE (ID_RECEPCION, ID_LEY))';
        EXECUTE IMMEDIATE 'CREATE INDEX IX_RLEY_LEY ON RECEPCION_LEYES(ID_LEY)';
    END IF;
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'LOTE_RECEPCIONES' AND COLUMN_NAME = 'PESO_FUNDIDO_G';
    IF n = 0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LOTE_RECEPCIONES ADD PESO_FUNDIDO_G NUMBER(14,3)'; END IF;
END;
/
PROMPT Relacion lotes-leyes disponible. Registros historicos conservados sin inferir leyes por color.
EXIT
