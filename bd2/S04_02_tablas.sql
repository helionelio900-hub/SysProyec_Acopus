-- 1. Tablas Cabecera-Detalle de Ventas Generales
CREATE TABLE BOM_VENTAS.VENTAS (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ESTADO      VARCHAR2(20) DEFAULT 'REGISTRADA' NOT NULL CHECK (ESTADO IN ('REGISTRADA', 'ANULADA')),
    TOTAL       NUMBER(12, 2) NOT NULL
);

CREATE TABLE BOM_VENTAS.DETALLE_VENTAS (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_VENTA        NUMBER NOT NULL,
    ID_PRODUCTO     NUMBER NOT NULL,
    NOMBRE_PRODUCTO VARCHAR2(120) NOT NULL,
    PRECIO_UNITARIO NUMBER(10, 2) NOT NULL,
    CANTIDAD        NUMBER(6) NOT NULL,
    SUBTOTAL        NUMBER(12, 2) NOT NULL,
    CONSTRAINT FK_DETALLE_VENTA FOREIGN KEY (ID_VENTA) REFERENCES BOM_VENTAS.VENTAS(ID) ON DELETE CASCADE
);

-- 2. Tablas Cabecera-Detalle de Liquidaciones Mayoristas de Oro (SITRA-ORO)
CREATE TABLE BOM_ACOPIO.DETALLE_LIQUIDACIONES_G1 (
    ID_DETALLE_LIQUIDACION  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_LIQUIDACION_G1       NUMBER NOT NULL,
    TIPO_ORO                VARCHAR2(10) NOT NULL CHECK (TIPO_ORO IN ('ROJO', 'VERDE')),
    PESO_FUNDIDO_G          NUMBER(10, 3) NOT NULL,
    PRECIO_GRAMO_PEN        NUMBER(10, 2) NOT NULL,
    SUBTOTAL_PEN            NUMBER(12, 2) NOT NULL,
    CONSTRAINT FK_DETALLE_LIQUIDACION_G1 FOREIGN KEY (ID_LIQUIDACION_G1) 
        REFERENCES BOM_ACOPIO.LIQUIDACIONES_G1(ID_LIQUIDACION_G1) ON DELETE CASCADE
);

-- Permisos para el usuario BOMERP_APP
GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_VENTAS.VENTAS TO BOMERP_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_VENTAS.DETALLE_VENTAS TO BOMERP_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_ACOPIO.DETALLE_LIQUIDACIONES_G1 TO BOMERP_APP;
