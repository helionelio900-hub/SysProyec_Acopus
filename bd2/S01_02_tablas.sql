-- BD2 - Sesion 01: Creación de Tablas del Sistema de Acopio y Liquidación de Oro
-- Propietario: BOM_ACOPIO | Usuario App Backend: BOMERP_APP
-- =============================================================================

-- 1. Tabla de Parámetros del Sistema / Cotizaciones Diarias
CREATE TABLE BOM_ACOPIO.PARAMETROS_SISTEMA (
    ID_PARAMETRO            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA                   DATE DEFAULT SYSDATE NOT NULL,
    PRECIO_DIARIO_GRAMO_PEN NUMBER(10, 2) NOT NULL,
    PORCENTAJE_MERMA_EST    NUMBER(5, 2) DEFAULT 5.00 NOT NULL,
    COTIZACION_ONZA_USD     NUMBER(10, 2),
    TIPO_CAMBIO_USD_PEN     NUMBER(6, 4),
    ESTADO                  VARCHAR2(10) DEFAULT 'ACTIVO' CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

-- 2. Tabla de Mineros (Clientes de Acopio)
CREATE TABLE BOM_ACOPIO.MINEROS (
    ID_MINERO               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DOCUMENTO_IDENTIDAD     VARCHAR2(15) NOT NULL UNIQUE,
    NOMBRES_APELLIDOS       VARCHAR2(150) NOT NULL,
    TELEFONO                VARCHAR2(20),
    ZONA_PROCEDENCIA        VARCHAR2(100),
    FECHA_REGISTRO          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 3. Tabla de Transacciones G2 (Acopiador Directo)
CREATE TABLE BOM_ACOPIO.TRANSACCIONES_G2 (
    ID_TRANSACCION_G2       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_MINERO               NUMBER NOT NULL,
    PESO_SIN_FUNDIR_G       NUMBER(10, 3) NOT NULL,
    PESO_FUNDIDO_NETO_G     NUMBER(10, 3) NOT NULL,
    TIPO_ORO                VARCHAR2(10) NOT NULL CHECK (TIPO_ORO IN ('ROJO', 'VERDE')),
    PRECIO_APLICADO_PEN     NUMBER(10, 2) NOT NULL,
    TOTAL_PAGADO_PEN        NUMBER(12, 2) NOT NULL,
    FECHA_TRANSACCION       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ID_LIQUIDACION_G1       NUMBER NULL,
    CONSTRAINT FK_G2_MINERO FOREIGN KEY (ID_MINERO) REFERENCES BOM_ACOPIO.MINEROS(ID_MINERO)
);

-- 4. Tabla de Liquidaciones Semanales G1 (Administrador Mayorista)
CREATE TABLE BOM_ACOPIO.LIQUIDACIONES_G1 (
    ID_LIQUIDACION_G1       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_ACOPIADOR_G2     VARCHAR2(150) NOT NULL,
    PESO_TOTAL_FUNDIDO_G    NUMBER(10, 3) NOT NULL,
    TIPO_ORO                VARCHAR2(10) NOT NULL CHECK (TIPO_ORO IN ('ROJO', 'VERDE')),
    COTIZACION_ONZA_USD     NUMBER(10, 2) NOT NULL,
    TIPO_CAMBIO_USD_PEN     NUMBER(6, 4) NOT NULL,
    PRECIO_RESULTANTE_GRAMO NUMBER(10, 2) NOT NULL,
    TOTAL_PAGADO_G2_PEN     NUMBER(12, 2) NOT NULL,
    FECHA_LIQUIDACION       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE BOM_ACOPIO.TRANSACCIONES_G2
    ADD CONSTRAINT FK_G2_LIQUIDACION_G1 FOREIGN KEY (ID_LIQUIDACION_G1)
    REFERENCES BOM_ACOPIO.LIQUIDACIONES_G1(ID_LIQUIDACION_G1);

-- Concesión de Permisos DML al Usuario ejecutor del Backend (BOMERP_APP)
GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_ACOPIO.PARAMETROS_SISTEMA TO BOMERP_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_ACOPIO.MINEROS TO BOMERP_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_ACOPIO.TRANSACCIONES_G2 TO BOMERP_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_ACOPIO.LIQUIDACIONES_G1 TO BOMERP_APP;
