-- S14 · Caja de cada centro de acopio, solo en soles (el acopiador no opera en dólares).
-- PAGO_COMPRA (lo pagado al minero) y PRESTAMO (préstamos entregados) los genera el sistema;
-- MAYORISTA (lo que pagó el mayorista), SALDO_INICIAL y MANUAL los registra el acopiador.
-- Solo el acopiador del centro ve su caja. Ejecutar como BOMERP_APP después de S14_04.
WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE TABLE ACOPIO_CAJA_MOVIMIENTOS (
    ID_MOVIMIENTO     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CENTRO_ACOPIO  NUMBER NOT NULL,
    FECHA             DATE NOT NULL,
    MONEDA            VARCHAR2(3) NOT NULL,
    INGRESO           BOOLEAN NOT NULL,
    ORIGEN            VARCHAR2(15) NOT NULL,
    MONTO             NUMBER(16,2) NOT NULL,
    CONCEPTO          VARCHAR2(200 CHAR) NOT NULL,
    ID_REFERENCIA     NUMBER,
    ANULADO           BOOLEAN DEFAULT FALSE NOT NULL,
    FECHA_CREACION    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_CAJA_ACOPIO_CENTRO FOREIGN KEY (ID_CENTRO_ACOPIO) REFERENCES CENTROS_ACOPIO (ID_CENTRO_ACOPIO),
    CONSTRAINT CK_CAJA_ACOPIO_MONEDA CHECK (MONEDA = 'PEN'),
    CONSTRAINT CK_CAJA_ACOPIO_ORIGEN CHECK (ORIGEN IN ('SALDO_INICIAL', 'MAYORISTA', 'MANUAL', 'PAGO_COMPRA', 'PRESTAMO')),
    CONSTRAINT CK_CAJA_ACOPIO_MONTO CHECK (MONTO > 0),
    CONSTRAINT CK_CAJA_ACOPIO_ORIGEN_TIPO CHECK (
        (ORIGEN IN ('SALDO_INICIAL', 'MAYORISTA') AND INGRESO = TRUE) OR
        (ORIGEN IN ('PAGO_COMPRA', 'PRESTAMO') AND INGRESO = FALSE AND MONEDA = 'PEN') OR
        ORIGEN = 'MANUAL')
);

CREATE INDEX IX_CAJA_ACOPIO_CENTRO_FECHA ON ACOPIO_CAJA_MOVIMIENTOS (ID_CENTRO_ACOPIO, FECHA);
CREATE INDEX IX_CAJA_ACOPIO_REFERENCIA ON ACOPIO_CAJA_MOVIMIENTOS (ORIGEN, ID_REFERENCIA);

