-- SITRA-ORO S08: registro de recepción de oro del acopiador por el mayorista.
-- Ejecutar una sola vez en el esquema BOMERP_APP después de S07.
-- Conserva los datos de mercado tal como los captura el operador; no calcula pagos.

CREATE TABLE MAYORISTA_RECEPCIONES (
    ID_RECEPCION               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA                      DATE NOT NULL,
    NOMBRE_ACOPIADOR            VARCHAR2(120) NOT NULL,
    ROJO_PESO_SIN_FUNDIR_G      NUMBER(10,3),
    ROJO_PESO_FUNDIDO_G         NUMBER(10,3),
    ROJO_ONZA                   VARCHAR2(80),
    ROJO_DOLAR                  VARCHAR2(80),
    ROJO_EXPORTACION            VARCHAR2(80),
    ROJO_PAGO_MATERIAL          VARCHAR2(80),
    VERDE_PESO_SIN_FUNDIR_G     NUMBER(10,3),
    VERDE_PESO_FUNDIDO_G        NUMBER(10,3),
    VERDE_ONZA                  VARCHAR2(80),
    VERDE_DOLAR                 VARCHAR2(80),
    VERDE_EXPORTACION           VARCHAR2(80),
    VERDE_PAGO_MATERIAL         VARCHAR2(80),
    DESCUENTO                   VARCHAR2(100),
    TOTAL                       VARCHAR2(100),
    FECHA_CREACION              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_MAY_REC_ROJO_PESOS CHECK (
        (ROJO_PESO_SIN_FUNDIR_G IS NULL AND ROJO_PESO_FUNDIDO_G IS NULL)
        OR (ROJO_PESO_SIN_FUNDIR_G IS NOT NULL AND ROJO_PESO_FUNDIDO_G IS NOT NULL
            AND ROJO_PESO_SIN_FUNDIR_G >= 0 AND ROJO_PESO_FUNDIDO_G >= 0)
    ),
    CONSTRAINT CK_MAY_REC_VERDE_PESOS CHECK (
        (VERDE_PESO_SIN_FUNDIR_G IS NULL AND VERDE_PESO_FUNDIDO_G IS NULL)
        OR (VERDE_PESO_SIN_FUNDIR_G IS NOT NULL AND VERDE_PESO_FUNDIDO_G IS NOT NULL
            AND VERDE_PESO_SIN_FUNDIR_G >= 0 AND VERDE_PESO_FUNDIDO_G >= 0)
    ),
    CONSTRAINT CK_MAY_REC_CON_PESO CHECK (
        ROJO_PESO_FUNDIDO_G IS NOT NULL OR VERDE_PESO_FUNDIDO_G IS NOT NULL
    )
);

CREATE INDEX IX_MAY_REC_FECHA ON MAYORISTA_RECEPCIONES (FECHA, ID_RECEPCION);
