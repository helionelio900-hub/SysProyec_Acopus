CREATE TABLE COTIZACIONES_COLOR (
 ID_COTIZACION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 COLOR VARCHAR2(5) NOT NULL CHECK (COLOR IN ('ROJO','VERDE')),
 ONZA_USD NUMBER(12,2) NOT NULL CHECK (ONZA_USD > 0),
 DOLAR_PEN NUMBER(10,4) NOT NULL CHECK (DOLAR_PEN > 0),
 EXPORTACION_PCT NUMBER(7,4) NOT NULL CHECK (EXPORTACION_PCT BETWEEN 0 AND 100),
 PRECIO_GRAMO_PEN NUMBER(16,2) NOT NULL CHECK (PRECIO_GRAMO_PEN >= 0),
 FECHA_PUBLICACION TIMESTAMP NOT NULL
);
