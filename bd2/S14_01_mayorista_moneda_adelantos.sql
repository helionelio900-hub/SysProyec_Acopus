-- S14 · Mayorista: pago en soles o dólares y adelantos a centros de acopio.
-- Ejecutar con el usuario dueño del esquema de la aplicación (BOMERP_APP) después de S09_15.
WHENEVER SQLERROR EXIT SQL.SQLCODE

-- 1. Moneda de pago del lote valorizado. TOTAL sigue en soles; TOTAL_PAGO_MONEDA es el mismo
--    importe en la moneda elegida (TOTAL / TIPO_CAMBIO_PAGO cuando se paga en USD).
ALTER TABLE MAYORISTA_RECEPCIONES ADD (
    MONEDA_PAGO        VARCHAR2(3) DEFAULT 'PEN' NOT NULL,
    TIPO_CAMBIO_PAGO   NUMBER(10,4),
    TOTAL_PAGO_MONEDA  NUMBER(18,2)
);
ALTER TABLE MAYORISTA_RECEPCIONES ADD CONSTRAINT CK_MAY_REC_MONEDA CHECK (
    MONEDA_PAGO IN ('PEN', 'USD')
    AND (MONEDA_PAGO = 'PEN' OR TIPO_CAMBIO_PAGO > 0)
);

-- 2. Adelantos entregados por el mayorista a un centro de acopio antes de recibir su oro.
--    Quedan PENDIENTES hasta descontarse en el pago de un lote (ID_RECEPCION).
CREATE TABLE MAYORISTA_ADELANTOS (
    ID_ADELANTO       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CENTRO_ACOPIO  NUMBER NOT NULL,
    FECHA             DATE NOT NULL,
    MONEDA            VARCHAR2(3) NOT NULL,
    MONTO             NUMBER(14,2) NOT NULL,
    TIPO_CAMBIO       NUMBER(10,4),
    MONTO_PEN         NUMBER(14,2) NOT NULL,
    OBSERVACION       VARCHAR2(200 CHAR),
    ESTADO            VARCHAR2(12) DEFAULT 'PENDIENTE' NOT NULL,
    ID_RECEPCION      NUMBER,
    FECHA_CREACION    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_ADELANTO_CENTRO FOREIGN KEY (ID_CENTRO_ACOPIO) REFERENCES CENTROS_ACOPIO (ID_CENTRO_ACOPIO),
    CONSTRAINT FK_ADELANTO_RECEPCION FOREIGN KEY (ID_RECEPCION) REFERENCES MAYORISTA_RECEPCIONES (ID_RECEPCION),
    CONSTRAINT CK_ADELANTO_MONEDA CHECK (MONEDA IN ('PEN', 'USD')),
    CONSTRAINT CK_ADELANTO_MONTOS CHECK (MONTO > 0 AND MONTO_PEN > 0),
    CONSTRAINT CK_ADELANTO_TC CHECK (MONEDA = 'PEN' OR TIPO_CAMBIO > 0),
    CONSTRAINT CK_ADELANTO_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'DESCONTADO', 'ANULADO')),
    CONSTRAINT CK_ADELANTO_DESCUENTO CHECK (
        (ESTADO = 'DESCONTADO' AND ID_RECEPCION IS NOT NULL) OR
        (ESTADO <> 'DESCONTADO' AND ID_RECEPCION IS NULL))
);

CREATE INDEX IX_ADELANTO_CENTRO_ESTADO ON MAYORISTA_ADELANTOS (ID_CENTRO_ACOPIO, ESTADO);
CREATE INDEX IX_ADELANTO_RECEPCION ON MAYORISTA_ADELANTOS (ID_RECEPCION);
CREATE INDEX IX_ADELANTO_FECHA ON MAYORISTA_ADELANTOS (FECHA);

-- 3. Vista de apoyo para el tablero: dinero que entra por día (valor del material valorizado por ley).
CREATE OR REPLACE VIEW V_MAYORISTA_INGRESO_DIARIO AS
SELECT r.FECHA,
       COUNT(DISTINCT r.ID_RECEPCION)                   AS LOTES,
       SUM(d.PESO_FUNDIDO_G)                            AS PESO_FUNDIDO_G,
       SUM(d.TOTAL_PEN)                                 AS INGRESO_PEN,
       ROUND(SUM(d.PRECIO_USD * d.PESO_FUNDIDO_G), 2)   AS INGRESO_USD
FROM MAYORISTA_RECEPCIONES r
JOIN RECEPCION_LEYES d ON d.ID_RECEPCION = r.ID_RECEPCION
WHERE NOT EXISTS (SELECT 1 FROM RECEPCION_ACUMULADA a WHERE a.ID_ORIGEN = r.ID_RECEPCION)
GROUP BY r.FECHA;

COMMIT;
