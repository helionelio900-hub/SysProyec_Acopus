WHENEVER SQLERROR EXIT SQL.SQLCODE
CREATE SEQUENCE SEQ_PONDERACION START WITH 1;
CREATE TABLE REG_PONDERACION (
 ID_REGISTRO NUMBER PRIMARY KEY,
 FECHA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 PESO_TOTAL NUMBER(18,3) NOT NULL,
 LECTURA NUMBER(10,7) NOT NULL,
 FUNDIDO NUMBER(18,3),
 CHECK (PESO_TOTAL > 0 AND LECTURA > 0 AND LECTURA <= 1),
 CHECK (FUNDIDO IS NULL OR (FUNDIDO >= 0 AND FUNDIDO <= PESO_TOTAL))
);
CREATE TABLE REG_PONDERACION_LEY (
 ID_REGISTRO NUMBER REFERENCES REG_PONDERACION(ID_REGISTRO) NOT NULL,
 NUMERO NUMBER NOT NULL,
 ID_LEY NUMBER REFERENCES LEYES_ORO(ID_LEY) NOT NULL,
 PESO NUMBER(10,3) NOT NULL CHECK (PESO > 0),
 PRIMARY KEY(ID_REGISTRO,NUMERO)
);
