WHENEVER SQLERROR EXIT SQL.SQLCODE
CREATE SEQUENCE SEQ_SOL_ENTREGA START WITH 1;
CREATE TABLE SOL_ENTREGA_MINERO (
 ID_SOLICITUD NUMBER PRIMARY KEY,
 ID_MINERO NUMBER NOT NULL REFERENCES MINEROS(ID_MINERO),
 ID_CENTRO_ACOPIO NUMBER NOT NULL REFERENCES CENTROS_ACOPIO(ID_CENTRO_ACOPIO),
 ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL CHECK (ESTADO IN ('PENDIENTE','ACEPTADA')),
 FECHA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE SOL_ENTREGA_PARTIDA (
 ID_SOLICITUD NUMBER NOT NULL REFERENCES SOL_ENTREGA_MINERO(ID_SOLICITUD),
 NUMERO NUMBER NOT NULL,
 COLOR VARCHAR2(5) NOT NULL CHECK (COLOR IN ('ROJO','VERDE')),
 PESO_CRUDO NUMBER(15,3) NOT NULL CHECK (PESO_CRUDO > 0),
 PESO_ESTIMADO NUMBER(15,3) NOT NULL,
 CONSTRAINT CK_SOL_PESOS CHECK (PESO_ESTIMADO > 0 AND PESO_ESTIMADO <= PESO_CRUDO),
 PRIMARY KEY (ID_SOLICITUD,NUMERO)
);
CREATE INDEX IX_SOL_ENT_CENTRO ON SOL_ENTREGA_MINERO(ID_CENTRO_ACOPIO,ESTADO);
CREATE INDEX IX_SOL_ENT_MINERO ON SOL_ENTREGA_MINERO(ID_MINERO,ID_CENTRO_ACOPIO);
