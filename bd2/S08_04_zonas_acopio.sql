-- Catálogo editable de zonas para los centros de acopio.
CREATE TABLE ZONAS_ACOPIO (
    ID_ZONA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    CONSTRAINT UK_ZONAS_ACOPIO_NOMBRE UNIQUE (NOMBRE)
);

