-- Conserva las zonas de centros ya registrados para que el catálogo y los datos existentes coincidan.
INSERT INTO ZONAS_ACOPIO (NOMBRE)
SELECT DISTINCT TRIM(c.ZONA)
  FROM CENTROS_ACOPIO c
 WHERE TRIM(c.ZONA) IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM ZONAS_ACOPIO z WHERE UPPER(z.NOMBRE) = UPPER(TRIM(c.ZONA)));
