-- Conserva las entregas originales y relaciona su analisis conjunto.
DECLARE
  existe NUMBER;
BEGIN
  SELECT COUNT(*) INTO existe FROM user_tables WHERE table_name = 'RECEPCION_ACUMULADA';
  IF existe = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE RECEPCION_ACUMULADA (
      ID_ORIGEN NUMBER(19) PRIMARY KEY,
      ID_ACUMULADA NUMBER(19) NOT NULL,
      CONSTRAINT FK_RAC_ORIGEN FOREIGN KEY (ID_ORIGEN) REFERENCES MAYORISTA_RECEPCIONES(ID_RECEPCION),
      CONSTRAINT FK_RAC_DESTINO FOREIGN KEY (ID_ACUMULADA) REFERENCES MAYORISTA_RECEPCIONES(ID_RECEPCION),
      CONSTRAINT CK_RAC_DISTINTA CHECK (ID_ORIGEN <> ID_ACUMULADA))';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_RAC_DESTINO ON RECEPCION_ACUMULADA(ID_ACUMULADA)';
  END IF;
END;
/
