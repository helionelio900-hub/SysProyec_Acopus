-- S14 · Reparación: crea las tablas de S09 que faltan tras recargar la base (solo si no existen).
-- Sin ellas fallan: listado de mineros y solicitudes de entrega (acopio), lotes de exportación,
-- análisis acumulado y registro de ponderación (mayorista). Ejecutar como BOMERP_APP.
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
  PROCEDURE crear(p_nombre VARCHAR2, p_tipo VARCHAR2, p_ddl VARCHAR2) IS
    v_existe NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_existe FROM user_objects WHERE object_name = p_nombre AND object_type = p_tipo;
    IF v_existe = 0 THEN
      EXECUTE IMMEDIATE p_ddl;
      DBMS_OUTPUT.PUT_LINE('Creado ' || p_tipo || ' ' || p_nombre);
    END IF;
  END;
BEGIN
  -- Secuencias (S09_09 / S09_15)
  crear('SEQ_SOL_ENTREGA', 'SEQUENCE', 'CREATE SEQUENCE SEQ_SOL_ENTREGA START WITH 100 INCREMENT BY 1 NOCACHE');
  crear('SEQ_PONDERACION', 'SEQUENCE', 'CREATE SEQUENCE SEQ_PONDERACION START WITH 100 INCREMENT BY 1 NOCACHE');

  -- Solicitudes de entrega del minero (S09_09 + S09_10)
  crear('SOL_ENTREGA_MINERO', 'TABLE', q'[
    CREATE TABLE SOL_ENTREGA_MINERO (
      ID_SOLICITUD NUMBER PRIMARY KEY,
      ID_MINERO NUMBER NOT NULL REFERENCES MINEROS(ID_MINERO),
      ID_CENTRO_ACOPIO NUMBER NOT NULL REFERENCES CENTROS_ACOPIO(ID_CENTRO_ACOPIO),
      ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
      FECHA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      ID_COMPRA_G2 NUMBER,
      CONSTRAINT CK_SOL_ESTADO CHECK (ESTADO IN ('PENDIENTE','ACEPTADA','COMPRA_REGISTRADA')),
      CONSTRAINT UQ_SOL_COMPRA UNIQUE (ID_COMPRA_G2),
      CONSTRAINT FK_SOL_COMPRA FOREIGN KEY (ID_COMPRA_G2) REFERENCES COMPRAS_G2(ID_COMPRA_G2))]');
  crear('SOL_ENTREGA_PARTIDA', 'TABLE', q'[
    CREATE TABLE SOL_ENTREGA_PARTIDA (
      ID_SOLICITUD NUMBER NOT NULL REFERENCES SOL_ENTREGA_MINERO(ID_SOLICITUD),
      NUMERO NUMBER NOT NULL,
      COLOR VARCHAR2(5) NOT NULL CHECK (COLOR IN ('ROJO','VERDE')),
      PESO_CRUDO NUMBER(15,3) NOT NULL CHECK (PESO_CRUDO > 0),
      PESO_ESTIMADO NUMBER(15,3) NOT NULL,
      CONSTRAINT CK_SOL_PESOS CHECK (PESO_ESTIMADO > 0 AND PESO_ESTIMADO <= PESO_CRUDO),
      PRIMARY KEY (ID_SOLICITUD, NUMERO))]');
  crear('IX_SOL_ENT_CENTRO', 'INDEX', 'CREATE INDEX IX_SOL_ENT_CENTRO ON SOL_ENTREGA_MINERO(ID_CENTRO_ACOPIO, ESTADO)');
  crear('IX_SOL_ENT_MINERO', 'INDEX', 'CREATE INDEX IX_SOL_ENT_MINERO ON SOL_ENTREGA_MINERO(ID_MINERO, ID_CENTRO_ACOPIO)');

  -- Recepciones dentro de un lote de exportación (S09_04 + columna PESO_FUNDIDO_G del maestro)
  crear('LOTE_RECEPCIONES', 'TABLE', q'[
    CREATE TABLE LOTE_RECEPCIONES (
      ID_RECEPCION NUMBER PRIMARY KEY REFERENCES MAYORISTA_RECEPCIONES(ID_RECEPCION),
      ID_LOTE NUMBER NOT NULL REFERENCES LOTES_EXPORTACION(ID_LOTE) ON DELETE CASCADE,
      PESO_ROJO_G NUMBER(10,3) NOT NULL CHECK (PESO_ROJO_G >= 0),
      PESO_VERDE_G NUMBER(10,3) NOT NULL CHECK (PESO_VERDE_G >= 0),
      PESO_FUNDIDO_G NUMBER(14,3))]');

  -- Análisis acumulado de varias entregas (S09_07)
  crear('RECEPCION_ACUMULADA', 'TABLE', q'[
    CREATE TABLE RECEPCION_ACUMULADA (
      ID_ORIGEN NUMBER(19) PRIMARY KEY,
      ID_ACUMULADA NUMBER(19) NOT NULL,
      CONSTRAINT FK_RAC_ORIGEN FOREIGN KEY (ID_ORIGEN) REFERENCES MAYORISTA_RECEPCIONES(ID_RECEPCION),
      CONSTRAINT FK_RAC_DESTINO FOREIGN KEY (ID_ACUMULADA) REFERENCES MAYORISTA_RECEPCIONES(ID_RECEPCION),
      CONSTRAINT CK_RAC_DISTINTA CHECK (ID_ORIGEN <> ID_ACUMULADA))]');
  crear('IX_RAC_DESTINO', 'INDEX', 'CREATE INDEX IX_RAC_DESTINO ON RECEPCION_ACUMULADA(ID_ACUMULADA)');

  -- Registro de ponderación de leyes (S09_15)
  crear('REG_PONDERACION', 'TABLE', q'[
    CREATE TABLE REG_PONDERACION (
      ID_REGISTRO NUMBER PRIMARY KEY,
      FECHA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      PESO_TOTAL NUMBER(18,3) NOT NULL,
      LECTURA NUMBER(10,7) NOT NULL,
      FUNDIDO NUMBER(18,3),
      CHECK (PESO_TOTAL > 0 AND LECTURA > 0 AND LECTURA <= 1),
      CHECK (FUNDIDO IS NULL OR (FUNDIDO >= 0 AND FUNDIDO <= PESO_TOTAL)))]');
  crear('REG_PONDERACION_LEY', 'TABLE', q'[
    CREATE TABLE REG_PONDERACION_LEY (
      ID_REGISTRO NUMBER NOT NULL REFERENCES REG_PONDERACION(ID_REGISTRO),
      NUMERO NUMBER NOT NULL,
      ID_LEY NUMBER NOT NULL REFERENCES LEYES_ORO(ID_LEY),
      PESO NUMBER(10,3) NOT NULL CHECK (PESO > 0),
      PRIMARY KEY (ID_REGISTRO, NUMERO))]');
END;
