-- S14 · Caja del mayorista en soles y dólares.
-- Ingresos del exportador y movimientos manuales los registra el mayorista; los pagos de lotes (PAGO_LOTE)
-- y los adelantos (ADELANTO) los genera el sistema y se anulan solos si el lote o el adelanto cambia.
-- Ejecutar como BOMERP_APP después de S14_01.
WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE TABLE MAYORISTA_CAJA_MOVIMIENTOS (
    ID_MOVIMIENTO   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA           DATE NOT NULL,
    MONEDA          VARCHAR2(3) NOT NULL,
    TIPO            VARCHAR2(8) NOT NULL,
    ORIGEN          VARCHAR2(15) NOT NULL,
    MONTO           NUMBER(16,2) NOT NULL,
    CONCEPTO        VARCHAR2(200 CHAR) NOT NULL,
    ID_REFERENCIA   NUMBER,
    ANULADO         BOOLEAN DEFAULT FALSE NOT NULL,
    FECHA_CREACION  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_CAJA_MONEDA CHECK (MONEDA IN ('PEN', 'USD')),
    CONSTRAINT CK_CAJA_TIPO CHECK (TIPO IN ('INGRESO', 'EGRESO')),
    CONSTRAINT CK_CAJA_ORIGEN CHECK (ORIGEN IN ('SALDO_INICIAL', 'EXPORTADOR', 'MANUAL', 'PAGO_LOTE', 'ADELANTO')),
    CONSTRAINT CK_CAJA_MONTO CHECK (MONTO > 0),
    CONSTRAINT CK_CAJA_ORIGEN_TIPO CHECK (
        (ORIGEN IN ('SALDO_INICIAL', 'EXPORTADOR') AND TIPO = 'INGRESO') OR
        (ORIGEN IN ('PAGO_LOTE', 'ADELANTO') AND TIPO = 'EGRESO') OR
        ORIGEN = 'MANUAL')
);

CREATE INDEX IX_CAJA_FECHA ON MAYORISTA_CAJA_MOVIMIENTOS (FECHA);
CREATE INDEX IX_CAJA_REFERENCIA ON MAYORISTA_CAJA_MOVIMIENTOS (ORIGEN, ID_REFERENCIA);

-- Saldo actual por moneda (los anulados no cuentan).
CREATE OR REPLACE VIEW V_MAYORISTA_CAJA_SALDO AS
SELECT MONEDA,
       SUM(CASE WHEN TIPO = 'INGRESO' THEN MONTO ELSE -MONTO END) AS SALDO
FROM MAYORISTA_CAJA_MOVIMIENTOS
WHERE ANULADO = FALSE
GROUP BY MONEDA;
