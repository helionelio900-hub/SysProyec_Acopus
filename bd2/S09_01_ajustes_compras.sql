-- Ejecutar una vez con el mismo usuario Oracle configurado en DB_USERNAME
-- para SITRA-ORO, donde ya existe la tabla TRANSACCIONES_G2.
-- Conserva las compras y liquidaciones existentes; no borra registros.
WHENEVER SQLERROR EXIT SQL.SQLCODE

ALTER TABLE TRANSACCIONES_G2 ADD (ANULADA NUMBER(1) DEFAULT 0 NOT NULL);
ALTER TABLE TRANSACCIONES_G2 ADD CONSTRAINT CK_G2_ANULADA CHECK (ANULADA IN (0, 1));

CREATE TABLE AJUSTES_COMPRA_G2 (
    ID_AJUSTE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TRANSACCION_G2 NUMBER NOT NULL,
    ID_CENTRO_ACOPIO NUMBER NOT NULL,
    ID_MINERO NUMBER NOT NULL,
    ID_RECEPCION_MAYORISTA NUMBER,
    ID_LIQUIDACION_G1 NUMBER,
    TIPO VARCHAR2(12) NOT NULL,
    ESTADO VARCHAR2(24) NOT NULL,
    MOTIVO VARCHAR2(500) NOT NULL,
    TIPO_ORO_ANTERIOR VARCHAR2(10) NOT NULL,
    PESO_SIN_FUNDIR_ANTERIOR NUMBER(10,3) NOT NULL,
    PESO_FUNDIDO_ANTERIOR NUMBER(10,3) NOT NULL,
    PRECIO_ANTERIOR NUMBER(10,2) NOT NULL,
    TOTAL_ANTERIOR NUMBER(12,2) NOT NULL,
    TIPO_ORO_NUEVO VARCHAR2(10),
    PESO_SIN_FUNDIR_NUEVO NUMBER(10,3),
    PESO_FUNDIDO_NUEVO NUMBER(10,3),
    PRECIO_NUEVO NUMBER(10,2),
    TOTAL_NUEVO NUMBER(12,2),
    SOLICITADO_POR VARCHAR2(40) NOT NULL,
    FECHA_SOLICITUD TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_DECISION_MINERO TIMESTAMP,
    DECIDIDO_POR_MINERO VARCHAR2(40),
    FECHA_DECISION_MAYORISTA TIMESTAMP,
    DECIDIDO_POR_MAYORISTA VARCHAR2(40),
    CONSTRAINT FK_AJUSTE_G2_COMPRA FOREIGN KEY (ID_TRANSACCION_G2)
        REFERENCES TRANSACCIONES_G2(ID_TRANSACCION_G2),
    CONSTRAINT FK_AJUSTE_G2_CENTRO FOREIGN KEY (ID_CENTRO_ACOPIO)
        REFERENCES CENTROS_ACOPIO(ID_CENTRO_ACOPIO),
    CONSTRAINT FK_AJUSTE_G2_MINERO FOREIGN KEY (ID_MINERO)
        REFERENCES MINEROS(ID_MINERO),
    CONSTRAINT CK_AJUSTE_G2_TIPO CHECK (TIPO IN ('EDICION', 'ANULACION')),
    CONSTRAINT CK_AJUSTE_G2_ESTADO CHECK (ESTADO IN
        ('PENDIENTE_MINERO', 'PENDIENTE_MAYORISTA', 'APROBADO', 'RECHAZADO_MINERO', 'RECHAZADO_MAYORISTA'))
);

CREATE INDEX IX_AJUSTE_G2_COMPRA ON AJUSTES_COMPRA_G2(ID_TRANSACCION_G2);
CREATE INDEX IX_AJUSTE_G2_MINERO_ESTADO ON AJUSTES_COMPRA_G2(ID_MINERO, ESTADO);
CREATE INDEX IX_AJUSTE_G2_CENTRO_ESTADO ON AJUSTES_COMPRA_G2(ID_CENTRO_ACOPIO, ESTADO);
CREATE UNIQUE INDEX UX_AJUSTE_G2_PENDIENTE ON AJUSTES_COMPRA_G2 (
    CASE WHEN ESTADO IN ('PENDIENTE_MINERO', 'PENDIENTE_MAYORISTA') THEN ID_TRANSACCION_G2 END
);
