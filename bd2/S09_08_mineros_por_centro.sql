-- Mineros aislados por centro. Solo asigna datos historicos con un origen inequivoco.
DECLARE
  existe NUMBER;
BEGIN
  SELECT COUNT(*) INTO existe FROM user_tab_columns WHERE table_name = 'MINEROS' AND column_name = 'ID_CENTRO_ACOPIO';
  IF existe = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE MINEROS ADD ID_CENTRO_ACOPIO NUMBER(19)';
    EXECUTE IMMEDIATE 'ALTER TABLE MINEROS ADD CONSTRAINT FK_MINERO_CENTRO FOREIGN KEY (ID_CENTRO_ACOPIO) REFERENCES CENTROS_ACOPIO(ID_CENTRO_ACOPIO)';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_MINERO_CENTRO ON MINEROS(ID_CENTRO_ACOPIO)';
  END IF;
END;
/
UPDATE MINEROS m SET ID_CENTRO_ACOPIO = (
  SELECT MIN(t.ID_CENTRO_ACOPIO) FROM TRANSACCIONES_G2 t WHERE t.ID_MINERO = m.ID_MINERO
) WHERE m.ID_CENTRO_ACOPIO IS NULL AND m.ID_MINERO IN (
  SELECT ID_MINERO FROM TRANSACCIONES_G2 WHERE ID_CENTRO_ACOPIO IS NOT NULL
  GROUP BY ID_MINERO HAVING COUNT(DISTINCT ID_CENTRO_ACOPIO) = 1
);
COMMIT;
SELECT COUNT(*) AS MINEROS_SIN_CENTRO FROM MINEROS WHERE ID_CENTRO_ACOPIO IS NULL;
