-- Ejecutar una sola vez en el mismo usuario/esquema donde se instaló
-- S01_03_tablas_bomerp_app.sql. No reemplaza ni duplica MINEROS.

CREATE TABLE CUENTAS_ACCESO (
    ID_CUENTA                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DOCUMENTO_IDENTIDAD        VARCHAR2(15) NOT NULL UNIQUE,
    CLAVE_HASH                  VARCHAR2(100) NOT NULL,
    ROL                         VARCHAR2(20) NOT NULL,
    ID_MINERO                   NUMBER,
    ID_CENTRO_ACOPIO_PREFERIDO NUMBER,
    ID_CENTRO_ACOPIO_ASIGNADO  NUMBER,
    ACTIVO                      NUMBER(1) DEFAULT 1 NOT NULL,
    FECHA_CREACION              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_CUENTAS_ROL CHECK (ROL IN ('MINERO', 'G2_ACOPIADOR', 'G1_MAYORISTA')),
    CONSTRAINT CK_CUENTAS_ACTIVO CHECK (ACTIVO IN (0, 1)),
    CONSTRAINT CK_CUENTAS_RELACION CHECK (
        (ROL = 'MINERO' AND ID_MINERO IS NOT NULL AND ID_CENTRO_ACOPIO_PREFERIDO IS NOT NULL AND ID_CENTRO_ACOPIO_ASIGNADO IS NULL)
        OR (ROL = 'G2_ACOPIADOR' AND ID_MINERO IS NULL AND ID_CENTRO_ACOPIO_PREFERIDO IS NULL)
        OR (ROL = 'G1_MAYORISTA' AND ID_MINERO IS NULL AND ID_CENTRO_ACOPIO_PREFERIDO IS NULL AND ID_CENTRO_ACOPIO_ASIGNADO IS NULL)
    ),
    CONSTRAINT FK_CUENTAS_MINERO FOREIGN KEY (ID_MINERO) REFERENCES MINEROS(ID_MINERO)
);

CREATE TABLE CENTROS_ACOPIO (
    ID_CENTRO_ACOPIO       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE                 VARCHAR2(120) NOT NULL,
    ZONA                   VARCHAR2(100) NOT NULL,
    DIRECCION              VARCHAR2(200) NOT NULL,
    TELEFONO               VARCHAR2(20),
    ID_CUENTA_ACOPIADOR    NUMBER NOT NULL UNIQUE,
    ACTIVO                 NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT UK_CENTRO_NOMBRE_ZONA UNIQUE (NOMBRE, ZONA),
    CONSTRAINT CK_CENTRO_ACTIVO CHECK (ACTIVO IN (0, 1)),
    CONSTRAINT FK_CENTRO_CUENTA FOREIGN KEY (ID_CUENTA_ACOPIADOR) REFERENCES CUENTAS_ACCESO(ID_CUENTA)
);

ALTER TABLE CUENTAS_ACCESO ADD CONSTRAINT FK_CUENTA_CENTRO_PREFERIDO
    FOREIGN KEY (ID_CENTRO_ACOPIO_PREFERIDO) REFERENCES CENTROS_ACOPIO(ID_CENTRO_ACOPIO);
ALTER TABLE CUENTAS_ACCESO ADD CONSTRAINT FK_CUENTA_CENTRO_ASIGNADO
    FOREIGN KEY (ID_CENTRO_ACOPIO_ASIGNADO) REFERENCES CENTROS_ACOPIO(ID_CENTRO_ACOPIO);

CREATE INDEX IX_CUENTAS_ROL_CENTRO_ACTIVO
    ON CUENTAS_ACCESO (ROL, ID_CENTRO_ACOPIO_PREFERIDO, ACTIVO);
