-- S14 · Préstamos del acopiador a sus mineros (solo soles) y descuento al pagar la compra.
-- Ejecutar como BOMERP_APP. Las compras existentes quedan con descuento 0.
WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE TABLE ACOPIO_PRESTAMOS_MINERO (
    ID_PRESTAMO       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CENTRO_ACOPIO  NUMBER NOT NULL,
    ID_MINERO         NUMBER NOT NULL,
    FECHA             DATE NOT NULL,
    MONTO_PEN         NUMBER(14,2) NOT NULL,
    OBSERVACION       VARCHAR2(200 CHAR),
    ESTADO            VARCHAR2(12) DEFAULT 'PENDIENTE' NOT NULL,
    ID_COMPRA_G2      NUMBER,
    FECHA_CREACION    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_PRESTAMO_CENTRO FOREIGN KEY (ID_CENTRO_ACOPIO) REFERENCES CENTROS_ACOPIO (ID_CENTRO_ACOPIO),
    CONSTRAINT FK_PRESTAMO_MINERO FOREIGN KEY (ID_MINERO) REFERENCES MINEROS (ID_MINERO),
    CONSTRAINT FK_PRESTAMO_COMPRA FOREIGN KEY (ID_COMPRA_G2) REFERENCES COMPRAS_G2 (ID_COMPRA_G2),
    CONSTRAINT CK_PRESTAMO_MONTO CHECK (MONTO_PEN > 0),
    CONSTRAINT CK_PRESTAMO_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'DESCONTADO', 'ANULADO')),
    CONSTRAINT CK_PRESTAMO_COMPRA CHECK (
        (ESTADO = 'DESCONTADO' AND ID_COMPRA_G2 IS NOT NULL) OR
        (ESTADO <> 'DESCONTADO' AND ID_COMPRA_G2 IS NULL))
);

CREATE INDEX IX_PRESTAMO_CENTRO_MINERO ON ACOPIO_PRESTAMOS_MINERO (ID_CENTRO_ACOPIO, ID_MINERO, ESTADO);
CREATE INDEX IX_PRESTAMO_COMPRA ON ACOPIO_PRESTAMOS_MINERO (ID_COMPRA_G2);

-- Descuento aplicado al pagar: préstamos + descuento manual (siempre en soles).
ALTER TABLE COMPRAS_G2 ADD (
    DESCUENTO_PEN         NUMBER(14,2) DEFAULT 0 NOT NULL,
    DESCUENTO_MANUAL_PEN  NUMBER(14,2) DEFAULT 0 NOT NULL
);
ALTER TABLE COMPRAS_G2 ADD CONSTRAINT CK_COMPRA_DESCUENTO CHECK (
    DESCUENTO_PEN >= 0 AND DESCUENTO_MANUAL_PEN >= 0 AND DESCUENTO_MANUAL_PEN <= DESCUENTO_PEN
);
